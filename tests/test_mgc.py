class TopFunction(unittest.TestCase):
    """`@top` emits a callable void function instead of a test `main`."""

    KERNEL_DECO = '@kernel("mgc_mm_os", check=(Y, Z), tol=0x11)\ndef mm_os():'
    CHECK = '\n        check(Y[:, :], Z[:, :], tol=0x11)\n'

    def top(self, deco='@top', fname='my_gemm', drop_check=True):
        src = _read(OS, 'mm_os.mgc')
        assert self.KERNEL_DECO in src
        src = src.replace(self.KERNEL_DECO, f'{deco}\ndef {fname}():')
        return src if drop_check else src.rstrip('\n') + self.CHECK

    def test_top_emits_function(self):
        c = _c(OS, 'mm_os.mgc', self.top())
        self.assertIn('void my_gemm(void)', c)
        self.assertNotIn('int main', c)
        self.assertNotIn('test.h', c)
        self.assertNotIn('return 0', c)
        self.assertNotIn('return errors', c)
        self.assertIn('return;', c)  # tiles with no work exit early

    def test_top_with_authors(self):
        c = _c(OS, 'mm_os.mgc', self.top('@top(authors=["A B <a@b.c>"])'))
        self.assertIn('// A B <a@b.c>', c)

    def notice(self, head):
        """The generated header of mm_os.mgc as a @top, with its leading comment block replaced by `head`."""
        src = self.top()
        src = head + src[src.index('\nfrom mgc import'):]
        c = _c(OS, 'mm_os.mgc', src)
        return c[:c.index('#include')]

    def test_notice_from_the_mgc_header(self):
        c = self.notice('# Copyright 2030 Someone Else.\n# SPDX-License-Identifier: MIT\n#\n# C D <c@d.e>\n#\n# About.\n')
        self.assertEqual(c, '// Copyright 2030 Someone Else.\n// SPDX-License-Identifier: MIT\n//\n// C D <c@d.e>\n//\n'
                            '// Generated by mgc from mm_os.mgc: do not edit, re-run mgc/mgcc.py.\n\n')

    def test_notice_without_license_or_authors(self):
        self.assertEqual(self.notice('# Just a description.\n'),
                         '// Generated by mgc from mm_os.mgc: do not edit, re-run mgc/mgcc.py.\n\n')

    def test_notice_authors_not_repeated(self):
        src = self.top('@top(authors=["C D <c@d.e>", "A B <a@b.c>"])')
        src = '# C D <c@d.e>\n' + src[src.index('\nfrom mgc import'):]
        c = _c(OS, 'mm_os.mgc', src)
        self.assertEqual(c.count('C D <c@d.e>'), 1)
        self.assertLess(c.index('C D'), c.index('A B'))

    def test_top_rejects_check(self):
        with self.assertRaisesRegex(MgcError, 'only available in @test'):
            _c(OS, 'mm_os.mgc', self.top(drop_check=False))

    def test_test_must_be_main(self):
        with self.assertRaisesRegex(MgcError, 'named `main`'):
            _c(OS, 'mm_os.mgc', self.top('@test("x")'))

    def test_kernel_rejects_check(self):
        src = _read(OS, 'mm_os.mgc').rstrip('\n') + self.CHECK
        with self.assertRaisesRegex(MgcError, 'has no check'):
            _c(OS, 'mm_os.mgc', src)

    def test_kernel_signature_and_test(self):
        e = Emitter(compile_module(_read(OS, 'mm_os.mgc'), 'mm_os.mgc', _hdr(OS)), 'mm_os.mgc')
